"""Build the regulation corpus (Pair B, stage 2 input) from the eCFR.

Usage (from repo root, venv active):
    python scripts/build_reg_corpus.py                  # latest eCFR date for Title 12
    python scripts/build_reg_corpus.py --date 2026-10-13

Downloads Parts 1005 (Reg E), 1006 (Reg F), 1022 (Reg V), 1026 (Reg Z), about
1 MB compressed, to data/raw/ecfr/ (git-ignored), then writes:
    data/processed/reg_chunks.parquet      retrieval chunks (schema: regs/parse.py Chunk)
    annotation/regulation_sections.md      section list for annotators (committed)
    outputs/reg_corpus_profile.json        counts and length stats
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from cfpb.config import OUTPUT_DIR, PROCESSED_DIR, RAW_DIR, ROOT  # noqa: E402
from cfpb.regs.ecfr import PARTS, fetch_part, latest_date  # noqa: E402
from cfpb.regs.parse import parse_part, to_records  # noqa: E402

NAMES = {"E": "Regulation E (Electronic Fund Transfers), 12 CFR Part 1005",
         "F": "Regulation F (Debt Collection Practices), 12 CFR Part 1006",
         "V": "Regulation V (Fair Credit Reporting), 12 CFR Part 1022",
         "Z": "Regulation Z (Truth in Lending), 12 CFR Part 1026"}


def write_section_list(sections: pd.DataFrame, date: str, path: Path) -> None:
    lines = [f"# Regulation section list (eCFR Title 12, as of {date})", "",
             "Generated by `scripts/build_reg_corpus.py`; do not edit by hand. Use it as the",
             "SECTION LIST in the annotation prompts (`annotation/ANNOTATION_GUIDE.md`).",
             "Gold labels use these section numbers; retrieval chunk ids start with them.", ""]
    for reg in ["E", "F", "V", "Z"]:
        part = sections[sections["regulation"] == reg]
        lines += [f"## {NAMES[reg]}", ""]
        for _, r in part.iterrows():
            tag = " *(reserved)*" if r["reserved"] else ""
            lines.append(f"- **{r['section']}** {r['title']}{tag}")
        lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=None, help="eCFR point-in-time date; default latest")
    args = ap.parse_args()
    date = args.date or latest_date()
    print(f"eCFR Title 12 as of {date}")

    raw_dir = RAW_DIR / "ecfr"
    records, sections = [], []
    for part, reg in PARTS.items():
        path = fetch_part(part, date, raw_dir)
        chunks, secs = parse_part(path, part, reg, date)
        records += to_records(chunks)
        sections += secs
        kinds = pd.Series([c.kind for c in chunks]).value_counts().to_dict()
        print(f"  Part {part} (Reg {reg}): {path.stat().st_size / 1e6:.2f} MB xml, "
              f"{sum(not s['reserved'] for s in secs)} sections, chunks {kinds}")

    df = pd.DataFrame(records)
    dupes = df["chunk_id"][df["chunk_id"].duplicated()].tolist()
    if dupes:
        sys.exit(f"Duplicate chunk ids: {dupes[:10]}")
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    df.to_parquet(PROCESSED_DIR / "reg_chunks.parquet", index=False)

    sec_df = pd.DataFrame(sections)
    write_section_list(sec_df, date, ROOT / "annotation" / "regulation_sections.md")

    profile = {
        "ecfr_date": date,
        "n_chunks": len(df),
        "chunks_by_kind": df["kind"].value_counts().to_dict(),
        "chunks_by_regulation_kind": {f"{r}/{k}": int(n) for (r, k), n in
                                      df.groupby(["regulation", "kind"]).size().items()},
        "sections_total": len(sec_df), "sections_reserved": int(sec_df["reserved"].sum()),
        "words_per_chunk": df.groupby("kind")["n_words"].describe().round(1).to_dict("index"),
        "word_window_splits": int(df["chunk_id"].str.contains("#").sum()),
    }
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "reg_corpus_profile.json").write_text(json.dumps(profile, indent=2))
    print(json.dumps({k: profile[k] for k in ("n_chunks", "chunks_by_kind", "sections_total",
                                               "sections_reserved", "word_window_splits")}))


if __name__ == "__main__":
    main()
